// ====== LANGUAGE SWITCHER LOGIC ======
const LANG_KEY = "sunAgroLang";
let currentLang = "en";

function t(key, fallback) {
  const dict = translations[currentLang] || translations.en;
  return dict && dict[key] ? dict[key] : fallback || key;
}

function applyLanguage(lang) {
  const dict = translations[lang];

  // For English, keep the HTML text as the source of truth so
  // that editing the HTML files directly updates the site.
  // Only apply dictionary-based replacements for non-English languages.

  currentLang = lang;

  const nodes = document.querySelectorAll("[data-i18n]");

  // Cache original English text or placeholder on first run
  nodes.forEach((el) => {
    if (!el.dataset.i18nOrig) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.dataset.i18nOrig = el.placeholder || "";
      } else {
        el.dataset.i18nOrig = el.textContent;
      }
    }
  });

  if (lang === "en") {
    // Restore original English from cached values
    nodes.forEach((el) => {
      const orig = el.dataset.i18nOrig;
      if (orig !== undefined) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.placeholder = orig;
        } else {
          el.textContent = orig;
        }
      }
    });
  } else if (dict) {
    // Apply non-English translations from dictionary
    nodes.forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.placeholder = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });
  }

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (_) {}
}

function initLanguage() {
  let lang = "en";
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && translations[stored]) lang = stored;
  } catch (_) {}

  applyLanguage(lang);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const selected = btn.dataset.lang;
      if (translations[selected]) {
        applyLanguage(selected);
      }
    });
  });
}

