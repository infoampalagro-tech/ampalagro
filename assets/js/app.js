function initHeroSlider() {
  const slider = document.querySelector(".hero-slider");
  if (!slider) return;

  const slides = slider.querySelectorAll(".slide");
  const dots = slider.querySelectorAll(".slider-dots .dot");
  if (!slides.length) return;

  let index = 0;
  let timer;

  function showSlide(i) {
    index = i;
    slides.forEach((s, idx) => {
      s.classList.toggle("active", idx === index);
    });
    dots.forEach((d, idx) => {
      d.classList.toggle("active", idx === index);
    });
  }

  function next() {
    const nextIndex = (index + 1) % slides.length;
    showSlide(nextIndex);
  }

  function startAuto() {
    stopAuto();
    timer = setInterval(next, 6000);
  }

  function stopAuto() {
    if (timer) clearInterval(timer);
  }

  // Dots click navigation
  dots.forEach((dot, idx) => {
    dot.addEventListener("click", () => {
      showSlide(idx);
      startAuto();
    });
  });

  // Pause on hover
  slider.addEventListener("mouseenter", stopAuto);
  slider.addEventListener("mouseleave", startAuto);

  showSlide(0);
  startAuto();
}

// ====== CONTACT FORM VALIDATION ======
function initContactForm() {
  const form = document.querySelector("form[data-contact-form]");
  if (!form) return;

  const fields = {
    name: form.querySelector("[name='name']"),
    phone: form.querySelector("[name='phone']"),
    email: form.querySelector("[name='email']"),
    message: form.querySelector("[name='message']")
  };
  const successEl = form.querySelector(".form-success");

  function showError(input, message) {
    const group = input.closest(".form-group");
    const errorEl = group && group.querySelector(".form-error");
    if (errorEl) {
      errorEl.textContent = message;
      errorEl.classList.add("visible");
    }
  }

  function clearErrors() {
    form.querySelectorAll(".form-error").forEach((el) => {
      el.classList.remove("visible");
    });
  }

  form.addEventListener("submit", (e) => {
    e.preventDefault();
    clearErrors();

    let valid = true;

    if (!fields.name.value.trim()) {
      showError(fields.name, t("contact.validation.nameRequired", "Name is required"));
      valid = false;
    }
    if (!fields.phone.value.trim()) {
      showError(fields.phone, t("contact.validation.phoneRequired", "Phone is required"));
      valid = false;
    }
    if (fields.email.value && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(fields.email.value)) {
      showError(
        fields.email,
        t("contact.validation.emailInvalid", "Enter a valid email")
      );
      valid = false;
    }
    if (!fields.message.value.trim()) {
      showError(
        fields.message,
        t("contact.validation.messageRequired", "Message is required")
      );
      valid = false;
    }

    if (!valid) return;

    form.reset();
    if (successEl) {
      successEl.classList.add("visible");
      successEl.textContent = t(
        "contact.success",
        "Thank you! Your enquiry has been received. We will contact you shortly."
      );
      setTimeout(() => {
        successEl.classList.remove("visible");
      }, 5000);
    }
  });
}

// ====== GALLERY FILTERS (optional) ======
function initGalleryFilters() {
  const container = document.querySelector(".gallery-filters");
  const items = document.querySelectorAll("[data-gallery-item]");
  if (!container || !items.length) return;

  container.addEventListener("click", (e) => {
    const btn = e.target.closest(".filter-btn");
    if (!btn) return;

    const filter = btn.dataset.filter;
    container.querySelectorAll(".filter-btn").forEach((b) => {
      b.classList.toggle("active", b === btn);
    });

    items.forEach((item) => {
      const type = item.dataset.type;
      if (!filter || filter === "all" || filter === type) {
        item.style.display = "";
      } else {
        item.style.display = "none";
      }
    });
  });
}

