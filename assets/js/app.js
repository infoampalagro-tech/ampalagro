// ====== MOBILE NAV ======
function initMobileNav() {
  const toggle = document.getElementById("navToggle");
  const nav = document.getElementById("mainNav");
  if (!toggle || !nav) return;

  const header = document.getElementById("siteHeader");

  const setOpen = (isOpen) => {
    toggle.classList.toggle("active", isOpen);
    nav.classList.toggle("open", isOpen);
    toggle.setAttribute("aria-expanded", String(isOpen));
    document.body.classList.toggle("nav-open", isOpen);
  };

  if (!toggle.hasAttribute("aria-expanded")) {
    toggle.setAttribute("aria-expanded", "false");
  }

  const isOpen = () => nav.classList.contains("open");

  toggle.addEventListener("click", () => {
    setOpen(!isOpen());
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      setOpen(false);
    });
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && isOpen()) {
      setOpen(false);
      toggle.focus();
    }
  });

  document.addEventListener("click", (e) => {
    if (!isOpen()) return;

    const target = e.target;
    if (!(target instanceof Element)) return;

    const clickInsideToggle = toggle.contains(target);
    const clickInsideNav = nav.contains(target);
    const clickInsideHeader = header ? header.contains(target) : false;

    if (clickInsideToggle || clickInsideNav) return;
    if (clickInsideHeader) return;

    setOpen(false);
  });
}

// ====== SCROLL REVEAL ======
function initScrollReveal() {
  const elements = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window)) {
    elements.forEach((el) => el.classList.add("visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.2 }
  );

  elements.forEach((el) => observer.observe(el));
}

